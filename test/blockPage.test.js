import { test, beforeEach } from 'node:test';
import assert from 'node:assert/strict';
import { parseBlockPage, isSecurityBlockPage, instrument, countedFetch } from '../api/_utils.js';
import diag from '../api/diag.js';
import * as store from '../api/_store.js';

const page = (reason) => `<html><body><h1>Your access to this site has been limited by the site owner</h1>
<p>Your access to this service has been limited. (HTTP response code 503)</p>
<h2>Block Technical Data</h2><table>
<tr><td>Block Reason:</td><td>${reason}</td></tr>
<tr><td>Time:</td><td>Mon, 16 Nov 2026</td></tr></table>
<p>Generated by Wordfence at Mon. Your IP: 18.140.1.2</p></body></html>`;

test('parses reason and IP from the Block Technical Data section', () => {
  const r = parseBlockPage(page('Blocked by Wordfence: too many requests (rate limit exceeded)'), 503);
  assert.equal(r.blocked, true);
  assert.match(r.reason, /rate limit/);
  assert.equal(r.blockedIp, '18.140.1.2');
  assert.ok(r.rawSnippet.length <= 300);
});

test('blocklist reason is returned verbatim', () => {
  assert.match(parseBlockPage(page('Blocked by Wordfence real-time IP blocklist'), 200).reason, /blocklist/);
});

test('detection does not depend on the exact banner sentence', () => {
  const r = parseBlockPage('<p>Wordfence: your access has been temporarily limited</p>', 429);
  assert.equal(r.blocked, true);
});

test('a bare 503 / 403 / 429 is a possible block; 200 and 404 are not', () => {
  assert.deepEqual([503, 403, 429].map((s) => parseBlockPage('<p>oops</p>', s).blocked), [true, true, true]);
  assert.equal(parseBlockPage('<p>oops</p>', 503).reason, 'http-503');
  assert.equal(parseBlockPage('<p>fine</p>', 200).blocked, false);
  assert.equal(parseBlockPage('<p>nope</p>', 404).blocked, false);
});

test('isSecurityBlockPage keeps its body-only behaviour', () => {
  assert.equal(isSecurityBlockPage(page('x')), true);
  assert.equal(isSecurityBlockPage('<p>menu</p>'), false);
});

test('outbound counter logs one count per countedFetch', async () => {
  const logs = [];
  const orig = console.log;
  console.log = (...a) => logs.push(a.join(' '));
  globalThis.fetch = async () => ({});
  await instrument('t', async () => { await countedFetch('x'); await countedFetch('y'); })();
  console.log = orig;
  assert.ok(logs.includes('[outbound] endpoint=t count=2'));
});

// ─── /api/diag ───────────────────────────────────────────────────────────────

let calls;
const run = async (token) => {
  let out;
  const res = { status(c) { out = { status: c }; return this; }, json(b) { out.body = b; } };
  await diag({ method: 'GET', query: { token } }, res);
  return out;
};

beforeEach(() => {
  store.clear();
  calls = [];
  console.log = () => {}; console.error = () => {};
  process.env.DIAG_TOKEN = 'secret';
  globalThis.fetch = async (url) => {
    calls.push(String(url));
    if (String(url).includes('ipify')) return { json: async () => ({ ip: '1.2.3.4' }) };
    if (String(url).includes('my-account')) return { status: 503, text: async () => page('Too many login attempts') };
    return { status: 200, text: async () => '<html>home</html>' };
  };
});

test('diag rejects a missing or wrong token without any outbound call', async () => {
  assert.equal((await run(undefined)).status, 404);
  assert.equal((await run('nope')).status, 404);
  assert.equal(calls.length, 0);
});

test('diag reports home and /my-account/ separately, with rawSnippet only when blocked', async () => {
  const r = await run('secret');
  assert.equal(r.status, 200);
  assert.equal(r.body.egressIp, '1.2.3.4');
  assert.equal(r.body.home.blocked, false);
  assert.equal(r.body.home.rawSnippet, undefined);
  assert.equal(r.body.myAccount.blocked, true);
  assert.match(r.body.myAccount.reason, /login attempts/);
  assert.ok(r.body.myAccount.rawSnippet);
});

test('diag serves a cached result for 60 s with no further outbound calls', async () => {
  await run('secret');
  const n = calls.length;
  const r = await run('secret');
  assert.equal(r.body.cached, true);
  assert.equal(calls.length, n);
});
